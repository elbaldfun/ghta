#!/usr/bin/env node
// Bundle content/blog/<locale>/<slug>.md into a TS module so posts ship as
// build-time data instead of being read from disk at request time. Runtime fs
// isn't available on edge/Workers hosts (and this makes blog pages SSG-fast
// everywhere). Re-run whenever blog content changes; build runs it first.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const DIR = join(process.cwd(), 'content', 'blog');
const out = {};
for (const locale of readdirSync(DIR)) {
  const dir = join(DIR, locale);
  if (!statSync(dir).isDirectory()) continue;
  out[locale] = {};
  for (const f of readdirSync(dir)) {
    if (!f.endsWith('.md')) continue;
    out[locale][f.replace(/\.md$/, '')] = readFileSync(join(dir, f), 'utf8');
  }
}

const dest = join(process.cwd(), 'src', 'lib', 'blog-generated.ts');
writeFileSync(
  dest,
  '// AUTO-GENERATED by scripts/gen-blog.mjs — do not edit. Run `npm run gen:blog`.\n' +
    '/* eslint-disable */\n' +
    'export const BLOG_RAW: Record<string, Record<string, string>> =\n' +
    JSON.stringify(out) +
    ';\n',
);
const n = Object.values(out).reduce((s, m) => s + Object.keys(m).length, 0);
console.log(`gen-blog: ${n} posts across ${Object.keys(out).length} locales -> ${dest}`);
